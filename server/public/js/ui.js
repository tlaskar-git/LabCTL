// Version footer, read from /api/health.
export function Footer() {
  const [version, setVersion] = useState('');
  useEffect(() => {
    api('/api/health', { allowUnauthorized: true })
      .then(d => setVersion(d.version || d.app_version || ''))
      .catch(() => {});
  }, []);
  return html`<footer class="app-footer">LabCTL${version ? ` v${version}` : ''}</footer>`;
}
